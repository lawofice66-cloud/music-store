function getTrackStats(id: string, title: string) {
  let hash = 0;
  for (let i = 0; i < title.length; i++) {
    hash = (hash * 37 + title.charCodeAt(i)) & 0x7fffffff;
  }
  const likes = 35 + (hash % 290);
  const plays = 520 + (hash % 4800);
  return { likes, plays };
}

export const GLOBAL_TRACKS_CATALOG: Track[] = RAW_TRACKS.map((t) => {
  const stats = getTrackStats(t.id, t.title);
  return {
    ...t,
    likes: t.likes ?? stats.likes,
    plays: t.plays ?? stats.plays,
  };
});

